  // 注入反查结果;此时 _typeId 落回默认的 postgresql。

  DesignTable readBack() => DesignTable()
    ..name = 'configs'
    ..schema = 'public'
    ..pkName = 'configs_pkey'
    ..columns.addAll([
      DesignColumn(
          name: 'id',
          type: 'int8',
          length: '64',
          notNull: true,
          primaryKey: true),
      DesignColumn(name: 'name', type: 'varchar', length: '32', comment: '名称'),
    ]);

  Widget editHarness(
          {Future<DesignTable?> Function(String, String, String?)? loader}) =>
      ChangeNotifierProvider(
        create: (_) => AppState(),
        child: MaterialApp(
          theme: ThemeData(brightness: Brightness.dark),
          home: Material(
            type: MaterialType.transparency,
            child: TableDesignerPage(
              title: 'configs (设计)',
